package webcontroller

import (
	"net/http"
	"time"

	"github.com/its-a-feature/Mythic/authentication/mythicjwt"

	"github.com/gin-gonic/gin"
	"github.com/its-a-feature/Mythic/authentication"
	"github.com/its-a-feature/Mythic/database"
	databaseStructs "github.com/its-a-feature/Mythic/database/structs"
)

type GenerateAPITokenInput struct {
	Input GenerateAPIToken `json:"input" binding:"required"`
}

type GenerateAPIToken struct {
	OperationID int      `json:"operation_id" binding:"required"`
	OperatorID  int      `json:"operator_id"`
	Name        string   `json:"name"`
	Scopes      []string `json:"scopes"`
}

type GenerateAPITokenResponse struct {
	OperationID  int       `json:"operation_id"`
	Status       string    `json:"status"`
	TokenType    string    `json:"token_type"`
	TokenValue   string    `json:"token_value"`
	Error        string    `json:"error"`
	ID           int       `json:"id"`
	OperatorID   int       `json:"operator_id"`
	Name         string    `json:"name"`
	CreatedBy    int       `json:"created_by"`
	Scopes       []string  `json:"scopes"`
	CreationTime time.Time `json:"creation_time"`
}

func GenerateAPITokenWebhook(c *gin.Context) {
	var input GenerateAPITokenInput
	err := c.ShouldBindJSON(&input)
	if err != nil {
		c.JSON(http.StatusBadRequest, GenerateAPITokenResponse{Status: "error", Error: err.Error()})
		return
	}
	issuerClaims, err := authentication.GetClaims(c)
	if err != nil {
		c.JSON(http.StatusUnauthorized, gin.H{"error": "Authentication Failed"})
		return
	}
	issuer, err := authentication.GetRequestUser(c)
	if err != nil {
		c.JSON(http.StatusUnauthorized, gin.H{"error": "Authentication Failed"})
		return
	}
	targetOperatorID := issuer.ID // default as a token for yourself
	if input.Input.OperatorID > 0 {
		targetOperatorID = input.Input.OperatorID
	}
	// Validate the issuer belongs to the target operation or is an admin
	var issuerRole string
	err = database.DB.Get(&issuerRole, `SELECT 
    	COALESCE((
    		SELECT view_mode 
    		FROM operatoroperation
    		WHERE operator_id=$1 AND operation_id=$2),'')
		`, issuer.ID, input.Input.OperationID)
	if err != nil || (!issuer.Admin && issuerRole == "") {
		c.JSON(http.StatusOK, GenerateAPITokenResponse{Status: "error", Error: "issuer does not have access to this operation"})
		return
	}
	// if the target is another user, make sure they're a bot account
	if targetOperatorID != issuer.ID {
		var target databaseStructs.Operator
		err = database.DB.Get(&target, `SELECT id,account_type FROM operator WHERE id=$1`, targetOperatorID)
		if err != nil ||
			target.AccountType != databaseStructs.AccountTypeBot ||
			(!issuer.Admin && issuerRole == database.OPERATOR_OPERATION_VIEW_MODE_SPECTATOR) {
			c.JSON(http.StatusOK, GenerateAPITokenResponse{Status: "error", Error: "tokens for another owner require an operation bot and a nonspectator issuer"})
			return
		}
	}
	name := input.Input.Name
	if name == "" {
		name = "autogenerated"
	}
	token := databaseStructs.Apitokens{
		OperatorID:  targetOperatorID,
		OperationID: input.Input.OperationID,
		CreatedBy:   issuer.ID,
		TokenType:   mythicjwt.AUTH_METHOD_API,
		Active:      true,
		Name:        name,
	}
	if issuerClaims.EventStepInstanceID > 0 {
		token.TokenType = mythicjwt.AUTH_METHOD_EVENT
		token.EventStepInstanceID.Valid = true
		token.EventStepInstanceID.Int64 = int64(issuerClaims.EventStepInstanceID)
	}
	issuerScopes, err := authentication.GetScopesSetFromClaims(c)
	if err != nil {
		c.AbortWithStatus(http.StatusUnauthorized)
		return
	}
	plain, err := database.CreateAPIToken(&token, input.Input.Scopes, issuerScopes, input.Input.OperationID)
	if err != nil {
		c.JSON(http.StatusOK, GenerateAPITokenResponse{Status: "error", Error: err.Error()})
		return
	}
	c.JSON(http.StatusOK, GenerateAPITokenResponse{
		Status:       "success",
		TokenValue:   plain,
		ID:           token.ID,
		OperatorID:   token.OperatorID,
		OperationID:  token.OperationID,
		Name:         token.Name,
		CreatedBy:    token.CreatedBy,
		TokenType:    token.TokenType,
		Scopes:       token.Scopes,
		CreationTime: token.CreationTime,
	})
}
