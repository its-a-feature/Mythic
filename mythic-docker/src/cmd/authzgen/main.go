// authzgen compiles repository-local Go declarations and Hasura metadata. It
// never connects to a database or a running Hasura, and --check never rewrites.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/its-a-feature/Mythic/authorization"
	databaseStructs "github.com/its-a-feature/Mythic/database/structs"
	"gopkg.in/yaml.v3"
)

func main() {
	check := flag.Bool("check", false, "check generated files without changing them")
	compiled := flag.Bool("compiled", false, "internal: newly discovered model registry has been compiled")
	flag.Parse()
	// Make targets run here; discovery is limited to actual model methods, not
	// naming conventions or a second list of tables that somebody must maintain.
	modelDir := "database/structs"
	modelFiles, err := filepath.Glob(filepath.Join(modelDir, "*.go"))
	if err != nil {
		panic(err)
	}
	providers := []string{}
	for _, name := range modelFiles {
		if strings.HasSuffix(name, "_test.go") || strings.HasSuffix(name, ".generated.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), name, nil, 0)
		if err != nil {
			panic(err)
		}
		for _, declaration := range file.Decls {
			method, ok := declaration.(*ast.FuncDecl)
			if !ok || method.Recv == nil || method.Name.Name != "AuthorizationPolicy" {
				continue
			}
			receiver, ok := method.Recv.List[0].Type.(*ast.Ident)
			if !ok {
				panic("AuthorizationPolicy must use a value receiver")
			}
			providers = append(providers, receiver.Name)
		}
	}
	sort.Strings(providers)
	var registry strings.Builder
	registry.WriteString("// Code generated by authzgen; DO NOT EDIT.\npackage databaseStructs\n\nimport (\n\"reflect\"\n\"github.com/its-a-feature/Mythic/authorization\"\n)\n\n// AuthorizationBindings is discovered from model methods, not maintained manually.\nfunc AuthorizationBindings() []authorization.ModelBinding {\nreturn []authorization.ModelBinding{\n")
	for _, provider := range providers {
		fmt.Fprintf(&registry, "{Type: reflect.TypeFor[%s](), Policy: (%s{}).AuthorizationPolicy()},\n", provider, provider)
	}
	registry.WriteString("}\n}\n")
	registryBytes, err := format.Source([]byte(registry.String()))
	if err != nil {
		panic(err)
	}
	registryPath := filepath.Join(modelDir, "authorization.generated.go")
	existing, _ := os.ReadFile(registryPath)
	if !bytes.Equal(existing, registryBytes) {
		if *check {
			fmt.Fprintln(os.Stderr, "stale model registry: run make build_authorization")
			os.Exit(1)
		}
		if *compiled {
			panic("model registry changed during generation")
		}
		if err := os.WriteFile(registryPath, registryBytes, 0644); err != nil {
			panic(err)
		}
		// Evaluate real Go policy values after compiling the discovered methods;
		// do not implement an interpreter for Go expressions in the generator.
		command := exec.Command("go", "run", "-tags=nomsgpack", "./cmd/authzgen", "-compiled")
		command.Stdout, command.Stderr = os.Stdout, os.Stderr
		if err := command.Run(); err != nil {
			os.Exit(1)
		}
		return
	}
	constants := map[string]string{}
	catalog, err := parser.ParseFile(token.NewFileSet(), "authorization/catalog.go", nil, 0)
	if err != nil {
		panic(err)
	}
	ast.Inspect(catalog, func(node ast.Node) bool {
		value, ok := node.(*ast.ValueSpec)
		if !ok {
			return true
		}
		for i, name := range value.Names {
			if i >= len(value.Values) {
				continue
			}
			if literal, ok := value.Values[i].(*ast.BasicLit); ok && literal.Kind == token.STRING {
				constants[name.Name], _ = strconv.Unquote(literal.Value)
			}
		}
		return true
	})
	routes := map[string][]string{}
	declaredRoutes := map[string]bool{}
	server, err := parser.ParseFile(token.NewFileSet(), "webserver/initialize.go", nil, 0)
	if err != nil {
		panic(err)
	}
	ast.Inspect(server, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok || len(call.Args) < 2 {
			return true
		}
		method, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || !strings.Contains(" POST GET PUT PATCH DELETE Any ", " "+method.Sel.Name+" ") {
			return true
		}
		literal, ok := call.Args[0].(*ast.BasicLit)
		if !ok || literal.Kind != token.STRING {
			return true
		}
		route, _ := strconv.Unquote(literal.Value)
		route = "/" + strings.TrimLeft(route, "/")
		routes[route] = []string{}
		for _, argument := range call.Args[1:] {
			middleware, ok := argument.(*ast.CallExpr)
			if !ok {
				continue
			}
			name, ok := middleware.Fun.(*ast.SelectorExpr)
			if !ok || name.Sel.Name != "TokenScopeMiddleware" {
				continue
			}
			declaredRoutes[route] = true
			if len(middleware.Args) != 1 {
				panic("TokenScopeMiddleware requires one declarative scope list")
			}
			if value, ok := middleware.Args[0].(*ast.Ident); ok && value.Name == "nil" {
				continue
			}
			list, ok := middleware.Args[0].(*ast.CompositeLit)
			if !ok {
				panic(route + ": scope lists must be literal declarations for offline generation")
			}
			for _, item := range list.Elts {
				selection, ok := item.(*ast.SelectorExpr)
				if !ok {
					panic(route + ": scope entries must reference catalog constants")
				}
				scope, known := constants[selection.Sel.Name]
				if !known {
					panic(route + ": unknown scope constant " + selection.Sel.Name)
				}
				routes[route] = append(routes[route], scope)
			}
		}
		return true
	})
	metadataDir := "../../hasura-docker/metadata"
	localMetadataDir := "authorization/hasura-metadata"
	// Generation always uses the deployed metadata as its input. Docker builds
	// only have src/, so their read-only check uses the last generated local copy.
	if *check {
		if _, err := os.Stat(metadataDir); os.IsNotExist(err) {
			metadataDir = localMetadataDir
		}
	}
	var actionSource struct {
		Actions []struct {
			Name       string `yaml:"name"`
			Definition struct {
				Handler string `yaml:"handler"`
			} `yaml:"definition"`
		} `yaml:"actions"`
	}
	actionBytes, err := os.ReadFile(filepath.Join(metadataDir, "actions.yaml"))
	if err != nil {
		if *check && metadataDir == localMetadataDir && os.IsNotExist(err) {
			fmt.Fprintln(os.Stderr, "missing local Hasura metadata: run make build_authorization in the repository before building the server image")
			os.Exit(1)
		}
		panic(err)
	}
	if err = yaml.Unmarshal(actionBytes, &actionSource); err != nil {
		panic(err)
	}
	actions := map[string]authorization.Action{}
	for _, model := range databaseStructs.AuthorizationBindings() {
		for _, action := range model.Policy.Actions {
			declaredRoutes[action.Handler] = true
		}
	}
	for _, action := range actionSource.Actions {
		handler := action.Definition.Handler
		if index := strings.Index(handler, "}}"); index >= 0 {
			handler = handler[index+2:]
		}
		handler = "/" + strings.TrimLeft(handler, "/")
		scopes, registered := routes[handler]
		if !registered {
			// Preserve obsolete Action definitions, but fail their preflight closed.
			actions[action.Name] = authorization.Action{Handler: handler, Unavailable: true}
			continue
		}
		if !declaredRoutes[handler] {
			panic(action.Name + ": add a scope declaration, explicit authenticated-only middleware, or a model Action policy")
		}
		actions[action.Name] = authorization.Action{Handler: handler, Permissions: scopes}
	}
	bindings, outputs, err := authorization.Compile(databaseStructs.AuthorizationBindings(), os.DirFS(metadataDir), actions, authorization.ScopeDefinitions())
	if err != nil {
		panic(err)
	}
	manifest, err := json.MarshalIndent(bindings, "", "  ")
	if err != nil {
		panic(err)
	}
	files := map[string][]byte{"authorization/metadata.generated.json": append(manifest, '\n')}
	for name, content := range outputs {
		files[filepath.Join(metadataDir, name)] = content
		if !*check {
			// Reuse the compiled bytes for the Docker copy; do not compile or
			// read the metadata again just to populate the build context.
			files[filepath.Join(localMetadataDir, name)] = content
		}
	}
	if !*check {
		// This directory contains only generator-owned copies. Replace it so
		// deleted metadata files cannot survive into the next Docker build.
		if err := os.RemoveAll(localMetadataDir); err != nil {
			panic(err)
		}
	}
	paths := []string{}
	for name := range files {
		paths = append(paths, name)
	}
	sort.Strings(paths)
	stale := false
	for _, name := range paths {
		content := files[name]
		existing, err := os.ReadFile(name)
		if err == nil && bytes.Equal(existing, content) {
			continue
		}
		if *check {
			fmt.Fprintln(os.Stderr, "stale authorization artifact:", name)
			stale = true
			continue
		}
		if err = os.MkdirAll(filepath.Dir(name), 0755); err != nil {
			panic(err)
		}
		if err = os.WriteFile(name, content, 0644); err != nil {
			panic(err)
		}
	}
	if stale {
		os.Exit(1)
	}
	fmt.Printf("Authorization: %d model policies, %d Actions; generated artifacts verified.\n", len(bindings.Tables), len(bindings.Actions))
}
